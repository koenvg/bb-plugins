import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const artifact = join(root, "vendor/koenvg-pi-openai-codex-speed-0.1.0.tgz");
const hash = createHash("sha256").update(readFileSync(artifact)).digest("hex");
if (hash !== "1642307063bd2867eb26e94853fd6906bc135c33161243de953012864b4718ff") {
  throw new Error(
    "Pinned Codex speed artifact hash mismatch. Do not regenerate from an unreviewed package.",
  );
}
const entry = fileURLToPath(import.meta.resolve("@koenvg/pi-openai-codex-speed"));
const capabilityModule = join(dirname(entry), "capabilities.js");
const capabilitySource = readFileSync(capabilityModule, "utf8");
const standaloneMessage =
  "super(`Speed: ${category}. Select /speed default or use /speed refresh.`);";
const managedMessage =
  "super(`Speed: ${category}. Select Default in the BB speed selector or use /speed refresh.`);";
if (capabilitySource.split(standaloneMessage).length !== 2) {
  throw new Error("Pinned SpeedError constructor changed. Review the BB recovery profile.");
}
const snapshotReuse = "if (!refresh && this.#snapshot?.key === auth.key)";
const freshSnapshotReuse =
  "if (!refresh && this.#snapshot?.key === auth.key && (this.#snapshot.error || this.#now() < this.#snapshot.expires))";
if (capabilitySource.split(snapshotReuse).length !== 2) {
  throw new Error("Pinned snapshot reuse predicate changed. Review the BB expiry profile.");
}
const managedCapabilitySource = capabilitySource
  .replace(standaloneMessage, managedMessage)
  .replace(snapshotReuse, freshSnapshotReuse);
const bundled = (
  await build({
    entryPoints: [entry],
    plugins: [
      {
        name: "bb-speed-profile",
        setup(builder) {
          builder.onLoad({ filter: /capabilities\.js$/ }, ({ path }) =>
            path === capabilityModule
              ? { contents: managedCapabilitySource, loader: "js" }
              : undefined,
          );
        },
      },
    ],
    bundle: true,
    platform: "node",
    target: "node24",
    format: "cjs",
    write: false,
    minify: true,
    legalComments: "none",
  })
).outputFiles[0].text;
const source = `
import { createRequire as __bbSpeedRequireFactory } from "node:module";
const __bbCodexSpeed = (() => {
  const require = __bbSpeedRequireFactory(import.meta.url);
  const module = { exports: {} };
  ${bundled}
  return module.exports;
})();
`;
const encodedSource = source
  .replaceAll("\\", "\\\\")
  .replaceAll("`", "\\`")
  .replaceAll("${", "\\${");
const output = `// Generated by bun run update:codex-speed. Do not edit the embedded package.\n// BB-managed recovery text and successful-snapshot expiry renewal.\n// @koenvg/pi-openai-codex-speed@0.1.0, artifact SHA-256 ${hash}\nexport const CODEX_SPEED_SOURCE = \`${encodedSource}\`;\n`;
const destination = join(root, "src/bridge/codex-speed-source.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output) {
    throw new Error(
      "Codex speed source differs from the pinned package. Run bun run update:codex-speed.",
    );
  }
} else {
  writeFileSync(destination, output);
}
